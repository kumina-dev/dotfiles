#!/usr/bin/env python3
"""Generate kitty's automatic light/dark themes from KDE's Breeze color schemes.

kitty (0.38+) switches between `light-theme.auto.conf` and `dark-theme.auto.conf`
when the desktop's light/dark preference changes, which KDE publishes through the
desktop portal. KumiOS Light/Dark therefore switches kitty too. Colors KDE defines
come from the installed Breeze Light/Dark schemes; the other ANSI colors keep
kitty's defaults. `--check` compares the committed files with a fresh generation.
"""
import argparse
import configparser
from pathlib import Path
import sys

SOURCE = Path(__file__).resolve().parent / "kitty"
SCHEMES = Path("/usr/share/color-schemes")
THEMES = {
    "light-theme.auto.conf": "BreezeLight",
    "dark-theme.auto.conf": "BreezeDark",
    # No portal preference: match KumiOS's default dark appearance.
    "no-preference-theme.auto.conf": "BreezeDark",
}
# kitty setting -> (KDE color group, key). ANSI colors without a Breeze
# counterpart (black, white, cyan and the bright variants) are not set.
MAPPING = (
    ("background", "Colors:View", "BackgroundNormal"),
    ("foreground", "Colors:View", "ForegroundNormal"),
    ("selection_background", "Colors:Selection", "BackgroundNormal"),
    ("selection_foreground", "Colors:Selection", "ForegroundNormal"),
    ("cursor", "Colors:View", "DecorationFocus"),
    ("url_color", "Colors:View", "ForegroundLink"),
    ("color1", "Colors:View", "ForegroundNegative"),   # red
    ("color2", "Colors:View", "ForegroundPositive"),   # green
    ("color3", "Colors:View", "ForegroundNeutral"),    # yellow
    ("color4", "Colors:View", "ForegroundLink"),       # blue
    ("color5", "Colors:View", "ForegroundVisited"),    # magenta
)


def hex_color(rgb):
    red, green, blue = (int(part) for part in rgb.split(",")[:3])
    return f"#{red:02x}{green:02x}{blue:02x}"


def render(scheme, schemes_dir=SCHEMES):
    colors = configparser.RawConfigParser(strict=False)
    colors.optionxform = str
    path = schemes_dir / f"{scheme}.colors"
    if not colors.read(path):
        raise FileNotFoundError(f"KDE color scheme not found: {path}")
    lines = [f"# Generated by plasma/kitty_theme.py from KDE's {scheme} color scheme.",
             "# Regenerate after KDE changes Breeze: python3 plasma/kitty_theme.py"]
    width = max(len(setting) for setting, _, _ in MAPPING)
    for setting, group, key in MAPPING:
        lines.append(f"{setting.ljust(width)} {hex_color(colors[group][key])}")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="report committed theme files that differ from KDE's schemes")
    args = parser.parse_args()
    stale = []
    for name, scheme in THEMES.items():
        text = render(scheme)
        target = SOURCE / name
        if args.check:
            if not target.is_file() or target.read_text() != text:
                stale.append(name)
        else:
            target.write_text(text)
            print(f"Wrote {target.relative_to(SOURCE.parent.parent)} from {scheme}")
    if args.check:
        print("kitty themes match KDE's Breeze schemes." if not stale
              else "Out of date with KDE's Breeze schemes: " + ", ".join(stale))
        return 1 if stale else 0
    return 0


if __name__ == "__main__":
    sys.exit(main())
